  function winnerText() {
    const scores = [0, 1, 2].map(teamScore);

    const maximum = Math.max(...scores);

    if (maximum === 0) {
      return "Ұпайлар әлі қойылмады";
    }

    const winners = scores
      .map((score, index) => ({
        score,
        name: `${index + 1}-команда`
      }))
      .filter(item => item.score === maximum);

    if (winners.length > 1) {
      return (
        "Тең нәтиже: " +
        winners.map(item => item.name).join(", ")
      );
    }

    return "Жеңімпаз — " + winners[0].name;
  }

