  document.addEventListener("click", event => {
    const button = event.target.closest("button");

    if (!button) return;

    // ТАЙМЕР

    if (button.id === "startTimer") {
      startTimer();
      return;
    }

    if (button.id === "pauseTimer") {
      pauseTimer();
      return;
    }

    if (button.id === "resetTimer") {
      resetTimer();
      return;
    }

    // АЛДЫҢҒЫ / КЕЛЕСІ

    if (button.id === "previous") {
      showPage(currentPage - 1);
      return;
    }

    if (button.id === "next") {
      showPage(currentPage + 1);
      return;
    }

    // КЕЗЕҢДЕР

    if (button.hasAttribute("data-stage")) {
      showPage(
        Number(button.dataset.stage)
      );
      return;
    }

    // ЖАУАПТАР

    if (button.hasAttribute("data-reveal")) {
      const answer = $(
        button.dataset.reveal
      );

      if (!answer) return;

      answer.classList.toggle("open");

      button.textContent =
        answer.classList.contains("open")
          ? "Жауапты жасыру"
          : "Жауабын көрсету";

      return;
    }

    // ҰПАЙ ҚОСУ / ҚАЙТАРУ

    if (button.hasAttribute("data-points")) {
      toggleAward(button);
      return;
    }

    if (button.id === "resetScores") {
      resetScores();
      return;
    }

    // СТУДЕНТ ТАҢДАУ

    if (button.id === "pickStudent") {
      pickStudent();
      return;
    }

    // ВИДЕО АУЫСТЫРУ

    if (button.hasAttribute("data-video")) {
      currentVideo = Number(
        button.dataset.video
      );

      videoMode = "youtube";

      renderVideo();
      return;
    }

    // ИНТЕРАКТИВТІ ТҮСІНДІРМЕ

    if (button.dataset.mode === "slides") {
      videoMode = "slides";
      slideIndex = 0;

      renderVideo();
      return;
    }

    // КӨРІНІСТЕРДІ АУЫСТЫРУ

    if (button.hasAttribute("data-slide")) {
      const direction = Number(
        button.dataset.slide
      );

      slideIndex = (
        slideIndex + direction + slides.length
      ) % slides.length;

      renderVideo();
      return;
    }
  });

