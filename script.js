  function saveScores() {
    try {
      localStorage.setItem(
        SCORE_KEY,
        JSON.stringify(awarded)
      );
    } catch (error) {
      // Браузерде сақтау бұғатталса,
      // ұпай санау жұмысын жалғастырады.
    }
  }

  function teamScore(team) {
    return Object.values(awarded[team]).reduce(
      (sum, value) =>
        sum + (Number(value) || 0),
      0
    );
  }

