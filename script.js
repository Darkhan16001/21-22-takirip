  function renderVideo() {
    const target = $("videoPlayer");

    if (!target) return;

    if (videoMode === "slides") {
      const item = slides[slideIndex];

      target.innerHTML = `
        <div class="slide">

          <div class="slide-icon">
            ${item.icon}
          </div>

          <h3>${item.title}</h3>

          <p>${item.text}</p>

          <div class="slide-counter">
            ${slideIndex + 1} / ${slides.length}
          </div>

        </div>

        <div class="video-buttons">

          <button data-slide="-1">
            ← Алдыңғы көрініс
          </button>

          <button data-slide="1">
            Келесі көрініс →
          </button>

        </div>
      `;
    } else {
      const video = videos[currentVideo];

      target.innerHTML = `
        <div class="video-frame">

          <iframe
            src="https://www.youtube-nocookie.com/embed/${video.id}?rel=0&playsinline=1"
            title="${video.title}"
            referrerpolicy="strict-origin-when-cross-origin"
            allow="accelerometer; autoplay; encrypted-media; gyroscope; picture-in-picture; web-share"
            allowfullscreen>
          </iframe>

        </div>

        <h3>${video.title}</h3>

        <p>${video.description}</p>

        <p>
          Арна: ${video.author}
        </p>

        <div class="video-buttons">

          <a
            href="https://www.youtube.com/watch?v=${video.id}"
            target="_blank"
            rel="noopener noreferrer">
            YouTube-та бөлек ашу
          </a>

          <button data-mode="slides">
            Видео ашылмаса — түсіндірме
          </button>

        </div>
      `;
    }

    document.querySelectorAll("[data-video]")
      .forEach(button => {

        const selected =
          videoMode === "youtube" &&
          Number(button.dataset.video) === currentVideo;

        button.classList.toggle(
          "active",
          selected
        );
      });
  }

