  const TOTAL_MS = 80 * 60 * 1000;

  let elapsedBeforeStart = 0;
  let startedAt = null;
  let timerInterval = null;

  function getElapsed() {
    return startedAt === null
      ? elapsedBeforeStart
      : elapsedBeforeStart + Date.now() - startedAt;
  }

  function formatTime(milliseconds) {
    const seconds = Math.floor(
      milliseconds / 1000
    );

    return (
      String(Math.floor(seconds / 60))
        .padStart(2, "0") +
      ":" +
      String(seconds % 60)
        .padStart(2, "0")
    );
  }

  function updateTimer() {
    const elapsed = Math.min(
      getElapsed(),
      TOTAL_MS
    );

    const remaining = Math.max(
      TOTAL_MS - elapsed,
      0
    );

    $("timer").textContent = formatTime(elapsed);

    $("remaining").textContent =
      remaining > 0
        ? "Қалғаны: " + formatTime(remaining)
        : "80 минут аяқталды";

    if (remaining === 0 && startedAt !== null) {
      pauseTimer();
    }
  }

  function startTimer() {
    if (startedAt !== null) return;

    if (elapsedBeforeStart >= TOTAL_MS) {
      elapsedBeforeStart = 0;
    }

    startedAt = Date.now();

    timerInterval = setInterval(
      updateTimer,
      500
    );

    updateTimer();
  }

  function pauseTimer() {
    if (startedAt === null) return;

    elapsedBeforeStart = Math.min(
      getElapsed(),
      TOTAL_MS
    );

    startedAt = null;

    clearInterval(timerInterval);
    timerInterval = null;

    updateTimer();
  }

  function resetTimer() {
    pauseTimer();
    elapsedBeforeStart = 0;
    updateTimer();
  }

